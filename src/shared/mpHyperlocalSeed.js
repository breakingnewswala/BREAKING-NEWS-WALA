function findReporterForDistrict(districtNameHi) {
  const match = MP_SEED_REPORTERS.find((r) =>
    r.assignedDistricts.some((d) => d === districtNameHi || districtNameHi.includes(d) || d.includes(districtNameHi))
  );
  return match || MP_SEED_REPORTERS[0];
}

export function buildAllDistrictAndCategoryArticles(existingArticles = []) {
  const publishedExisting = existingArticles.filter((a) => a.status === 'PUBLISHED');
  const coveredDistrictIds = new Set(publishedExisting.map((a) => a.districtId));
  const coveredCategoryIds = new Set(publishedExisting.map((a) => a.categoryId));

  const generated = [];

  // 1. Ensure EVERY single one of the 55 MP districts has at least 1 rich published article
  MP_55_DISTRICTS.forEach((dist, idx) => {
    if (coveredDistrictIds.has(dist.id)) return;
    const topic = TOPIC_LIBRARY[idx % TOPIC_LIBRARY.length];
    const rep = findReporterForDistrict(dist.nameHi);
    const id = `art-mp-${dist.slug}`;
    const views = 2800 + ((idx * 397) % 9400);
    const shares = 180 + ((idx * 73) % 1200);

    generated.push({
      id,
      slug: `${dist.slug}-${topic.categoryId}-report`,
      title: topic.titleFn(dist.nameHi),
      summary: topic.summaryFn(dist.nameHi),
      content: topic.bodyFn(dist.nameHi),
      status: 'PUBLISHED',
      priority: idx % 9 === 0 ? 'HIGH' : 'NORMAL',
      featuredImage: topic.photo,
      imageCaption: `${dist.nameHi} जिले से ब्रेकिंग न्यूज़ वाला की विशेष ग्राउंड रिपोर्ट।`,
      imageAttribution: `${rep.name} (${rep.badgeNumber})`,
      categoryId: topic.categoryId,
      categoryName: topic.categoryName,
      districtId: dist.id,
      districtName: dist.nameHi,
      divisionId: dist.divisionId,
      authorId: rep.id,
      authorName: rep.name,
      authorRole: rep.role === 'trusted_reporter' ? 'वरिष्ठ जिला संवाददाता' : 'जिला संवाददाता',
      isBreaking: idx % 14 === 0,
      viewCount: views,
      shareCount: shares,
      createdAt: `${(idx % 6) + 1} घंटे पहले`,
      publishedAt: `${(idx % 6) + 1} घंटे पहले`,
      factChecked: true,
      factCheckScore: 95 + (idx % 5),
      tags: [dist.nameHi, ...topic.tags],
    });
    coveredDistrictIds.add(dist.id);
    coveredCategoryIds.add(topic.categoryId);
  });

  // 2. Ensure ALL 11 categories explicitly have multiple strong stories
  TOPIC_LIBRARY.forEach((topic, idx) => {
    const existingInCat = [...publishedExisting, ...generated].filter((a) => a.categoryId === topic.categoryId).length;
    if (existingInCat < 2) {
      const dist = MP_55_DISTRICTS[idx % MP_55_DISTRICTS.length];
      const rep = findReporterForDistrict(dist.nameHi);
      generated.push({
        id: `art-cat-${topic.categoryId}`,
        slug: `${topic.categoryId}-${dist.slug}-special`,
        title: topic.titleFn(dist.nameHi),
        summary: topic.summaryFn(dist.nameHi),
        content: topic.bodyFn(dist.nameHi),
        status: 'PUBLISHED',
        priority: 'HIGH',
        featuredImage: topic.photo,
        imageCaption: `${topic.categoryName} विशेष रिपोर्ट — ${dist.nameHi}`,
        imageAttribution: `${rep.name} (बीएनडब्ल्यू ब्यूरो)`,
        categoryId: topic.categoryId,
        categoryName: topic.categoryName,
        districtId: dist.id,
        districtName: dist.nameHi,
        divisionId: dist.divisionId,
        authorId: rep.id,
        authorName: rep.name,
        authorRole: 'वरिष्ठ संवाददाता',
        isBreaking: topic.categoryId === 'cat-top' || topic.categoryId === 'cat-crime',
        viewCount: 6400 + idx * 410,
        shareCount: 620 + idx * 45,
        createdAt: '2 घंटे पहले',
        publishedAt: '2 घंटे पहले',
        factChecked: true,
        factCheckScore: 97,
        tags: [topic.categoryName, dist.nameHi, 'मध्य प्रदेश'],
      });
    }
  });

  return generated;
}

